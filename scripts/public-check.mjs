// Приёмочный сценарий (интерфейс после редизайна): «Добавить урок» → импорт готового урока → «Готово к офлайну» → офлайн → перезагрузка
// → t2 (только s3: «ответ верный» + «найди вторую деталь», затем + s4 без повторного выбора ответа) → перезагрузка → прогресс 2 из 3;
// переключение языка + перезагрузка (язык сохраняется); горизонтальная прокрутка. Профили: ноутбук 1440 и телефон 390×844 (касания).
// При падении сохраняет trace. Запуск: node scripts/public-check.mjs [url] [lesson.json]
import { chromium, devices } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
const URL_ = process.argv[2] ?? 'https://ughhfu40-collab.github.io/adiadffrvvcv/';
const FILE = process.argv[3] ?? 'docs/pitch/lesson-kk-after-teacher.json';
const OUT = process.env.OUT_DIR ?? '.demo/public-check';
mkdirSync(OUT, { recursive: true });
const lesson = JSON.parse(readFileSync(FILE, 'utf8'));
const [t1, t2] = lesson.tasks;
const b = await chromium.launch();
const summary = {};
let failed = false;
for (const [name, dev] of [['laptop', { ...devices['Desktop Chrome'], viewport: { width: 1440, height: 900 } }], ['phone', { ...devices['Pixel 7'], viewport: { width: 390, height: 844 } }]]) {
  const ctx = await b.newContext({ ...dev, serviceWorkers: 'allow' });
  await ctx.tracing.start({ screenshots: true, snapshots: true });
  const p = await ctx.newPage();
  const r = (summary[name] = { steps: {} });
  let step = 'открыть сайт';
  const ok = (k, v = true) => { r.steps[k] = v; };
  const noHScroll = () => p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth);
  const offlineProbe = () => p.evaluate(() => fetch(`${location.origin}/__probe?${Date.now()}`, { cache: 'no-store' }).then(() => false, () => true));
  try {
    await p.goto(URL_);
    r.build = await p.getByTestId('build').innerText();
    r.homeNoHScroll = await noHScroll();
    ok('startButtonInViewport', await p.getByTestId('start-lesson').evaluate((el) => { const b = el.getBoundingClientRect(); return b.top >= 0 && b.bottom <= window.innerHeight; }));
    step = 'импорт JSON';
    await p.getByTestId('import-open').click();
    r.fileBefore = await p.getByTestId('import-filename').innerText();
    await p.getByTestId('import-file').setInputFiles(FILE);
    await p.getByTestId('import-ok').waitFor();
    r.fileAfter = await p.getByTestId('import-filename').innerText();
    ok('import', r.fileBefore === 'Файл не выбран' && r.fileAfter.endsWith(FILE.split('/').pop()));
    step = '«Готово к офлайну»';
    await p.locator('[data-testid="offline-status"][data-ready="true"]').waitFor({ timeout: 60_000 });
    ok('offlineReady');
    step = 'отключить сеть и перезагрузить';
    await ctx.setOffline(true);
    await p.reload();
    await p.getByTestId(`lesson-${lesson.id}`).waitFor();
    ok('networkBlocked', await offlineProbe());
    if (!r.steps.networkBlocked) throw new Error('сеть не отключилась');
    ok('lessonAfterOfflineReload');
    step = 't1';
    await p.getByTestId(`lesson-${lesson.id}`).click();
    await p.getByTestId(`opt-${t1.correctOptionId}`).check();
    for (const s of t1.evidenceSets[0]) await p.getByTestId(`sent-${s}`).click();
    await p.getByTestId('check').click();
    await p.locator('[data-testid="feedback"][data-solved="true"]').waitFor();
    await p.getByTestId('next').click();
    step = 't2: верный ответ + только s3';
    await p.getByTestId(`opt-${t2.correctOptionId}`).check();
    await p.getByTestId('sent-s3').click();
    await p.getByTestId('check').click();
    const fb = p.getByTestId('feedback');
    await fb.waitFor();
    r.t2OnlyS3 = { answer: await fb.getAttribute('data-answer'), evidence: await fb.getAttribute('data-evidence'), solved: await fb.getAttribute('data-solved'),
      answerLine: await p.getByTestId('feedback-answer').innerText(), tip: await p.getByTestId('feedback-tip').innerText() };
    if (r.t2OnlyS3.evidence !== 'missing' || r.t2OnlyS3.answer !== 'true') throw new Error(`ожидалось «не хватает доказательства», получено ${JSON.stringify(r.t2OnlyS3)}`);
    const tipOk = lesson.language === 'kk' ? r.t2OnlyS3.tip.startsWith('Екінші деректі тап') : r.t2OnlyS3.tip.startsWith('Найди вторую деталь');
    if (!tipOk) throw new Error(`подсказка не про вторую деталь: ${r.t2OnlyS3.tip}`);
    ok('t2AsksForMoreEvidence');
    r.lessonNoHScroll = await noHScroll();
    await p.screenshot({ path: `${OUT}/${name}-t2-missing.png` });
    step = 't2: добавить s4';
    const answerKept = await p.getByTestId(`opt-${t2.correctOptionId}`).isChecked();
    ok('answerKeptAfterFeedback', answerKept);
    await p.getByTestId('sent-s4').click();
    await p.getByTestId('check').click();
    await p.locator('[data-testid="feedback"][data-solved="true"]').waitFor();
    ok('t2SolvedWithS3S4');
    step = 'перезагрузка и прогресс';
    await p.locator('button', { hasText: /←/ }).first().click();
    await p.reload();
    await p.getByTestId(`lesson-${lesson.id}`).waitFor();
    ok('stillOffline', await offlineProbe());
    r.progress = (await p.getByTestId(`lesson-${lesson.id}`).innerText()).match(/Выполнено \d+ из \d+/)?.[0];
    if (r.progress !== 'Выполнено 2 из 3') throw new Error(`прогресс: ${r.progress}`);
    ok('progressAfterReload');
    step = 'язык интерфейса';
    await p.getByTestId('ui-lang').click();
    await p.getByText('Дағдылар бойынша прогресс').waitFor();
    await p.reload();
    await p.getByText('Дағдылар бойынша прогресс').waitFor();
    ok('kkPersistedAfterReload');
    r.kkCard = (await p.getByTestId(`lesson-${lesson.id}`).innerText()).split('\n').pop();
    ok('kkUi', r.kkCard?.includes('2-і орындалды') ?? false);
    r.homeNoHScrollKk = await noHScroll();
    await p.screenshot({ path: `${OUT}/${name}-home-kk.png`, fullPage: true });
    await p.reload();
    ok('kkPersisted', await p.getByText('Дағдылар бойынша прогресс').isVisible());
    await p.getByTestId('ui-lang').click();
    await p.getByText('Прогресс по навыкам').waitFor();
    ok('ruUiBack');
    r.homeNoHScrollRu = await noHScroll();
    await ctx.tracing.stop();
  } catch (e) {
    failed = true;
    r.failedStep = step;
    r.error = String(e.message ?? e).split('\n')[0];
    r.trace = `${OUT}/${name}-trace.zip`;
    await ctx.tracing.stop({ path: r.trace });
  }
  await ctx.close();
}
await b.close();
console.log(JSON.stringify(summary, null, 2));
process.exit(failed ? 1 : 0);
